-- R1·C-5 M2|移除 `schedule_def` —— **它是一張沒有 reader 的表,而它編碼了一個錯的裁定。**
--
-- ## 為什麼建了又移除
--
-- M0 的 OQ-SCH-1 建議開放「通知派送 / 提醒」與「回收桶到期清理」。
-- M1 照著建了 `schedule_def`(CHECK 允許 `notification` / `trashPurge`)。
-- 準備做 M2 時去對碼,發現那個建議把**兩件不同的事混成一項**:
--
-- | 項目 | 實際是什麼 | 該不該讓租戶設時間 |
-- |---|---|---|
-- | Ragic 的「**提醒**」 | 日期欄驅動的**每日批次掃描**,會寄信給人 | 該。但**我方根本還沒有這個功能**(全 repo 零命中) |
-- | 我方的 `notifications.dispatch` | **每分鐘**排空 `notification_delivery` 佇列 | **不該** —— 那是投遞延遲不是排程 |
--
-- 🔴 而「投遞延遲不該開放」正是 **M0 自己寫的原則**:
--   「`event-fanout` / `webhook-delivery` / `trigger-async` 刻意不開 ——
--    那是**投遞延遲**不是排程,開放只會讓人把它調慢然後抱怨慢。」
-- `notification-dispatcher` 是同一個形狀,而我在列開放清單時沒認出來。
--
-- ## 剩下的那一項不值得為它做一張設定頁
--
-- 扣掉上面兩個,只剩 `trashPurge`。而它**不寄任何東西給任何人** ——
-- Ragic 那張清單上的項目幾乎都是「送東西給人」或「把資料拉進來」,
-- 時間才有意義。硬刪已過保留期的垃圾桶資料,幾點發生使用者感覺不到。
--
-- ## 真正該讓人設時間的東西,已經有更好的做法了
--
-- **定時觸發**(C-5 M3/M4)是**逐條各自設時刻**,比 Ragic 的「一項功能一個時間、
-- 套用到該租戶所有實例」更細。使用者要的「每天 8 點做某件事」已經做得到。
--
-- ## 處置
--
-- 依本 repo 既有先例(`fieldLayoutSchema.sectionId` / `colWidths` / `rowHeights`
-- 皆因零 reader 被移除):**留著一張沒有 reader 的表,就是留著一個會被當成
-- 「已經設計好只差接線」的假承諾。** 等真的有「提醒」或「定期寄報表」時再建,
-- 那時它的形狀才會由真實需求決定,而不是由一個混淆的建議決定。
DROP TABLE IF EXISTS "schedule_def";

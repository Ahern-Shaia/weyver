-- R1·C-5|定時觸發要有身分。
--
-- 🔴 C-4 明文拒絕「系統身分」:
--   「一旦有系統身分,『我看不到那張表,但我可以設一條觸發器往裡面寫』就成立了。」
-- 而排程**沒有觸發者** —— 若沿用 C-4 非同步側「actor 為 null → 記 denied」的規則,
-- 定時觸發就永遠不會跑。
--
-- 解法是記住**是誰建的**,並以他的身分執行。建觸發器需要 `design` 權(C-4 裁定),
-- 那已經是很高的授權,以他的身分跑不會擴權。
--
-- ⚠️ 代價誠實記:建立者離職 / 被停權後,那條定時觸發會開始記 `denied`。
-- **那是可見的失敗不是靜默的** —— 執行紀錄看得到,與簽核人離職卡簽同一種處理哲學。
